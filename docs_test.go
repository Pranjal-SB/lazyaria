// The reference pages are generated from the code: the help text and flag
// sets of the commands, and the settings schema. This test rewrites them
// with -update-docs (see the go:generate line in main.go) and otherwise
// fails when the committed pages are out of date.
var updateDocs = flag.Bool("update-docs", false, "rewrite docs/reference from the code")

func TestReferenceDocs(t *testing.T) {
	pages := map[string]string{
		"docs/reference/commands.md": commandsDoc(),
		"docs/reference/settings.md": settingsDoc(),
		"docs/reference/keys.md":     keysDoc(),
	}
	for path, want := range pages {
		if *updateDocs {
			if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		got, err := os.ReadFile(path)
		if err != nil || string(got) != want {
			t.Errorf("%s is out of date; regenerate it with: go generate .", path)
		}
	}
}

// The docs folder is the Pages site, which serves docs/install.sh as
// https://pranjal-sb.github.io/lazyaria/install.sh. It must stay the same
// as install.sh; -update-docs copies it.
func TestInstallScriptCopy(t *testing.T) {
	src, err := os.ReadFile("install.sh")
	if err != nil {
		t.Fatal(err)
	}
	if *updateDocs {
		if err := os.WriteFile("docs/install.sh", src, 0o755); err != nil {
			t.Fatal(err)
		}
		return
	}
	if got, err := os.ReadFile("docs/install.sh"); err != nil || !bytes.Equal(got, src) {
		t.Error("docs/install.sh differs from install.sh; copy it with: go generate .")
	}
}

const generatedNote = "<!-- Generated by `go generate .` from the code. Do not edit by hand. -->\n"

// commandsDoc is the overall help, then one section per command with its
// help entry and, where it has flags, the flag list the command prints for -h.
func commandsDoc() string {
	var b strings.Builder
	b.WriteString("# Commands\n\n" + generatedNote + `
Every command is ` + "`lazyaria <command> [args]`" + `. Flags may come before
or after the other arguments, and take one or two dashes (` + "`-wait`" + ` and
` + "`--wait`" + ` are the same). A job is named by its number, ` + "`14`" + ` or
` + "`#14`" + ` as ` + "`lazyaria list`" + ` shows it, or by the first characters of its
ID, as long as they match only one job. Numbers are never reused.

Commands that talk to the daemon start it when it is not running. See
[The daemon](../concepts/the-daemon.md).

## Overview

This is what ` + "`lazyaria help`" + ` prints:

` + "```text\n" + usage + "```\n")

	entries := helpEntries()
	names := make([]string, 0, len(commands))
	for name := range commands {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		fmt.Fprintf(&b, "\n## %s\n\n", name)
		if e := entries[name]; e != "" {
			b.WriteString("```text\n" + e + "```\n")
		}
		var help bytes.Buffer
		commands[name](context.Background(), []string{"-h"}, io.Discard, &help)
		// Only a flag set prints "Usage of"; other commands reject -h.
		if _, flags, ok := strings.Cut(help.String(), ":\n"); ok && flags != "" && strings.HasPrefix(help.String(), "Usage of ") {
			b.WriteString("\nFlags:\n\n```text\n" + flags + "```\n")
		}
	}
	return b.String()
}

// helpEntries splits the usage text into one entry per command. An entry
// starts at a line indented by two spaces; "pause|resume" belongs to both.
func helpEntries() map[string]string {
	out := map[string]string{}
	var cur []string
	for _, line := range strings.SplitAfter(usage, "\n") {
		switch {
		case strings.HasPrefix(line, "  ") && !strings.HasPrefix(line, "   "):
			cur = strings.Split(strings.Fields(line)[0], "|")
			for _, c := range cur {
				out[c] = strings.TrimPrefix(line, "  ")
			}
		case strings.HasPrefix(line, "   "):
			for _, c := range cur {
				out[c] += strings.TrimPrefix(line, "  ")
			}
		default:
			cur = nil
		}
	}
	return out
}

// keysDoc is the terminal interface's key table.
func keysDoc() string {
	var b strings.Builder
	b.WriteString("# Keys\n\n" + generatedNote + `
These are the keys of the terminal interface, which ` + "`lazyaria`" + ` opens when
you run it with no command. ` + "`?`" + ` shows the same list on screen. Keys
in a dialog are listed in [The terminal interface](../guides/terminal-interface.md).

| Keys | What they do |
|---|---|
`)
	for _, k := range tui.KeyHelp() {
		keys := make([]string, len(k.Keys))
		for i, key := range k.Keys {
			keys[i] = "`" + key + "`"
		}
		fmt.Fprintf(&b, "| %s | %s |\n", strings.Join(keys, " "), k.Help)
	}
	return b.String()
}

// settingsDoc is one table per section of the settings schema.
func settingsDoc() string {
	var b strings.Builder
	b.WriteString("# Settings\n\n" + generatedNote + `
lazyaria reads its settings from these places. A later one wins over an
earlier one:

1. The built-in default, shown below.
2. The config file, ` + "`~/.config/lazyaria/config.toml`" + ` (see
   [Files and paths](files-and-paths.md)).
3. An environment variable: ` + "`LAZYARIA_`" + ` and the key in capitals, with
   dots as underscores. ` + "`downloads.dir`" + ` is ` + "`LAZYARIA_DOWNLOADS_DIR`" + `.
4. A value saved with ` + "`lazyaria config set`" + `. ` + "`lazyaria config reset`" + `
   removes it again.
5. A command-line flag, such as ` + "`lazyaria daemon --mode`" + `.

` + "`lazyaria config list`" + ` shows every key, its current value and where the
value came from. ` + "`lazyaria config list --json`" + ` prints the same as JSON,
with the type, default, allowed values and help text of each key, and
` + "`not_used_yet`" + `, which is true for a setting nothing reads yet.

In the config file, each section below is a TOML table:

` + "```toml\nversion = 1\n\n[downloads]\nmax_concurrent = 3\nmin_split_size = \"8M\"\n```\n" + `
Sizes are a number with an optional K, M, G or T (1K is 1024 bytes).
Durations are written like ` + "`30s`" + `, ` + "`5m`" + ` or ` + "`1h`" + `. On the command line a list is
comma separated (` + "`429,network`" + `); in the file it is a TOML array.

The **Applies** column says when a change takes effect: **now**, or after
the daemon **restarts**. Settings marked *Not used yet* are for features
that are not built yet; nothing reads them. ` + "`lazyaria config list`" + `
marks them ` + "`(not used yet)`" + `, and ` + "`lazyaria config set`" + ` saves one with a
warning.
`)
	section := ""
	for _, e := range config.Schema() {
		sec, _, ok := strings.Cut(e.Key, ".")
		if !ok {
			sec = "general"
		}
		if sec != section {
			section = sec
			fmt.Fprintf(&b, "\n## %s\n\n| Setting | Default | Applies | Description |\n|---|---|---|---|\n", sec)
		}
		applies := "restart"
		if e.Live {
			applies = "now"
		}
		desc := e.Help
		if len(e.Enum) > 0 {
			desc += " One of: `" + strings.Join(e.Enum, "`, `") + "`."
		}
		if e.Unused {
			desc += " *Not used yet.*"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", e.Key, defaultCell(e.Value), applies, strings.ReplaceAll(desc, "|", `\|`))
	}
	b.WriteString(`
The config file may also hold one ` + "`keys.<action>`" + ` list per action, and a
` + "`[theme]`" + ` table with one ` + "`theme.<role>`" + ` colour per role. *Not used yet.*
`)
	return b.String()
}

func defaultCell(v any) string {
	s := fmt.Sprint(v)
	if l, ok := v.([]string); ok {
		s = strings.Join(l, ",")
	}
	if s == "" {
		return "empty"
	}
	return "`" + strings.ReplaceAll(s, "|", `\|`) + "`"
}
